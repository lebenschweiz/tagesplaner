const DAY_MS = 864e5;
const gcd = (a, b) => (b ? gcd(b, a % b) : a);

/**
 * Satz für ein Datum (YYYY-MM-DD). Ein fester Schrittweiten-Lauf durch die Liste:
 * Jeder Satz kommt genau einmal vor, bevor sich etwas wiederholt, und Nachbartage
 * liegen in der Liste weit auseinander (keine zwei Sprichwörter hintereinander).
 */
export function quoteFor(date, offset = 0) {
  const [y, m, d] = date.split("-").map(Number);
  const dayNo = Math.round(Date.UTC(y, m - 1, d) / DAY_MS);
  const n = QUOTES.length;
  let step = Math.round(n * 0.382) || 1;            // goldener Schnitt: gut verteilt
  while (gcd(step, n) !== 1) step++;
  const i = (((dayNo + offset) * step) % n + n) % n;
  return QUOTES[i];
}
