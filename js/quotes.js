const DAY = 864e5;
const gcd = (a, b) => (b ? gcd(b, a % b) : a);
// Schrittweite teilerfremd zur Anzahl -> jede Zahl 0..N-1 kommt genau einmal pro Durchlauf vor.
// ~0.618·N verteilt aufeinanderfolgende Tage weit über die Liste (keine Themenblöcke).
const N = QUOTES.length;
let STEP = Math.round(N * 0.618);
while (gcd(STEP, N) !== 1) STEP++;

/** Spruch für ein Datum (YYYY-MM-DD). Innerhalb von N Tagen nie doppelt. */
export function quoteFor(isoDate) {
  const [y, m, d] = isoDate.split("-").map(Number);
  const day = Math.round(Date.UTC(y, m - 1, d) / DAY);
  return QUOTES[(((day * STEP) % N) + N) % N];
}
